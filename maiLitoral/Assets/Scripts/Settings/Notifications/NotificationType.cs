/* Enumeration used to identify all reusable notification types */

public enum NotificationType {
    PopularBeaches, // Notifications related to popular beaches based on beach ranking
    QuietBeaches, // Notifications related to quiet and relaxing beaches
    FamilyBeaches, // Notifications related to family friendly beaches
    BeachState, // Notifications related to newly added beaches and beach properties
    WeatherNews // Notifications related to litoral weather updates
}